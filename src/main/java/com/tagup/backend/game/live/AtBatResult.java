package com.tagup.backend.game.live;

/**
 * 타석 결과. 세계관 용어 "아웃 / 세이프"에 대응한다.
 *
 * <p><b>왜 안타/아웃이 아니라 아웃/세이프인가</b> — KBO 응답에는 출루 사유(안타·볼넷·실책)가 없다.
 * 출루했다는 사실만 알 수 있어 "안타 여부"는 판정 불가다. 반면 아웃/출루는 아웃카운트·스코어·주자
 * 변화로 확정할 수 있어, 배팅을 이 2지선다로 정의하면 자동 정산이 100% 가능하다. (I-011)
 */
public enum AtBatResult {
    /** 타자가 아웃됨 */
    OUT,
    /** 타자가 살아나감 (안타·볼넷·실책 등 사유 불문) */
    SAFE,
    /** 판정 근거 부족 — 배팅 정산에 쓰면 안 된다 */
    UNKNOWN
}
